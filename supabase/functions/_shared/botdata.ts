// Database lookups shared by the Telegram and WhatsApp bots (and the chat registration flow).
// All of them talk to Supabase with the service role, so they must only be used inside Edge Functions.

type Json = Record<string, any>;

const SUPABASE_URL = Deno.env.get("SUPABASE_URL") ?? "";
const SERVICE_KEY = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY") ?? "";

export const q = (v: string) => encodeURIComponent(v);
export const inList = (ids: string[]) => `in.(${ids.map((x) => encodeURIComponent(`"${x}"`)).join(",")})`;
export const last10 = (v: unknown) => String(v ?? "").replace(/\D/g, "").slice(-10);

// One REST call. Returns the parsed JSON, or null when the call failed.
export async function rest(path: string, init: RequestInit = {}): Promise<any> {
  const res = await fetch(`${SUPABASE_URL}/rest/v1/${path}`, {
    ...init,
    headers: {
      apikey: SERVICE_KEY, Authorization: `Bearer ${SERVICE_KEY}`,
      "Content-Type": "application/json", ...(init.headers ?? {}),
    },
  });
  return res.ok ? await res.json().catch(() => null) : null;
}

/* ---- who is behind a phone number / an email ----
   students.phone10 / whatsapp10 and tutors.mobile10 / whatsapp10 are the last 10 digits of the number
   (generated by the database, indexed); email_lc is the lower-cased e-mail. Exact matches, so these stay fast
   however many people are registered. */

const STUDENT_COLS = "student_id,student_name,whatsapp,phone,email_lc,blocked_at,notifications_off";
const TUTOR_COLS = "tutor_id,full_name,whatsapp_number,mobile_number,blocked_at,notifications_off";

export async function accountsByPhone(phone: unknown): Promise<{ students: Json[]; tutors: Json[] }> {
  const p = last10(phone);
  if (p.length < 10) return { students: [], tutors: [] };
  const [s1, s2, t1, t2] = await Promise.all([
    rest(`students?phone10=eq.${p}&select=${STUDENT_COLS}`),
    rest(`students?whatsapp10=eq.${p}&select=${STUDENT_COLS}`),
    rest(`tutors?whatsapp10=eq.${p}&select=${TUTOR_COLS}`),
    rest(`tutors?mobile10=eq.${p}&select=${TUTOR_COLS}`),
  ]);
  const uniq = (rows: Json[], key: string) => [...new Map(rows.map((r) => [r[key], r])).values()];
  // brothers / sisters registered with the same email (but another number) belong to this parent too
  const emails = [...new Set([...(s1 ?? []), ...(s2 ?? [])].map((r: Json) => String(r.email_lc ?? "")).filter(Boolean))];
  const s3 = emails.length ? await rest(`students?email_lc=${inList(emails)}&select=${STUDENT_COLS}`) : [];
  return {
    students: uniq([...(s1 ?? []), ...(s2 ?? []), ...(s3 ?? [])], "student_id").sort((a, b) => String(a.student_id).localeCompare(String(b.student_id))),
    tutors: uniq([...(t1 ?? []), ...(t2 ?? [])], "tutor_id"),
  };
}

export async function studentEmailTaken(email: string): Promise<boolean> {
  const rows = await rest(`students?email_lc=eq.${q(String(email).trim().toLowerCase())}&select=student_id&limit=1`);
  return !!rows?.length;
}

export async function studentPhoneTaken(phone: unknown): Promise<boolean> {
  const p = last10(phone);
  if (p.length < 10) return false;
  const rows = await rest(`students?or=(phone10.eq.${p},whatsapp10.eq.${p})&select=student_id&limit=1`);
  return !!rows?.length;
}

/* ---- the life of a tuition, as the bot menus show it ---- */

export const declined = (a: Json) => !!(a.parent_rejected || a.tutor_rejected);

export function applicationState(a: Json) {
  if (a.classes_completed) return "completed";
  if (a.parent_accepted && a.tutor_accepted && a.demo_date) return "running";
  if (a.demo_date) return "scheduled";
  return "applied";
}

const RANK = ["running", "scheduled", "applied", "completed"];

export type Life = {
  demo: string; subject: string; mode: string;
  sid: string;               // the student of the tuition
  cat: string;               // running | scheduled | new (finding tutor / applied) | completed
  app: Json | null;          // the application that decides the category
  tutorIds: string[]; apps: Json[];
  student: Json | null;      // tutor menu only: the student of that tuition
};

const COLS = "demo_id,tutor_id,parent_accepted,tutor_accepted,parent_rejected,tutor_rejected,classes_completed,demo_date,demo_time,class_duration,billing_plan,class_dates,class_start_date,student_next_due_date,tutor_next_payment_date";

// role "s": the tuitions of these students;  role "t": the tuitions these tutors applied for
export async function loadLife(role: string, ids: string[]): Promise<Life[]> {
  const out: Life[] = [];
  if (role === "s") {
    const tuitions = await rest(`tuitions?student_id=${inList(ids)}&terminated=eq.false&select=demo_id,subject,student_id,medium&order=posted_at.desc`) ?? [];
    const apps = tuitions.length ? await rest(`applications?demo_id=${inList(tuitions.map((t: Json) => t.demo_id))}&select=${COLS}`) ?? [] : [];
    for (const t of tuitions) {
      const mine = apps.filter((a: Json) => a.demo_id === t.demo_id && !declined(a));
      const best = RANK.find((r) => mine.some((a: Json) => applicationState(a) === r));
      const app = mine.find((a: Json) => applicationState(a) === best) ?? null;
      out.push({ demo: t.demo_id, subject: String(t.subject ?? ""), mode: String(t.medium ?? ""), sid: String(t.student_id), cat: !best || best === "applied" ? "new" : best, app, tutorIds: mine.map((a: Json) => String(a.tutor_id)), apps: mine, student: null });
    }
  } else {
    const apps = (await rest(`applications?tutor_id=${inList(ids)}&select=${COLS}`) ?? []).filter((a: Json) => !declined(a));
    const tuitions = apps.length ? await rest(`tuitions?demo_id=${inList(apps.map((a: Json) => a.demo_id))}&terminated=eq.false&select=demo_id,subject,student_id,medium`) ?? [] : [];
    const studs = tuitions.length ? await rest(`students?student_id=${inList([...new Set(tuitions.map((t: Json) => String(t.student_id)))] as string[])}&select=student_id,student_name,class_name,board,city,pin_code`) ?? [] : [];
    for (const a of apps) {
      const t = tuitions.find((x: Json) => x.demo_id === a.demo_id);
      if (!t) continue;
      const st = applicationState(a);
      out.push({ demo: t.demo_id, subject: String(t.subject ?? ""), mode: String(t.medium ?? ""), sid: String(t.student_id), cat: st === "applied" ? "new" : st, app: a, tutorIds: [String(a.tutor_id)], apps: [a], student: studs.find((x: Json) => x.student_id === t.student_id) ?? null });
    }
  }
  return out;
}
